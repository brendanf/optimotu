test_that("is_placeholder works", {
  expect_false(is_placeholder("Nonea"))
  expect_false(is_placeholder("Nonea_pulla"))
  expect_true(is_placeholder("none"))
  expect_true(is_placeholder("None"))
  expect_true(is_placeholder("unknown"))
  expect_true(is_placeholder("unassigned"))
  expect_true(is_placeholder("Unclassified_Fungi"))
  expect_true(is_placeholder("Unknown-Fungi"))
  expect_true(is_placeholder("uncultured fungus"))
  expect_true(is_placeholder("environmental_sample"))
  expect_true(is_placeholder("dummy_1"))
  expect_true(is_placeholder("Ascomycota incertae sedis"))
  expect_true(is_placeholder("incertae_sedis"))
  expect_true(is_placeholder("Ascomycota_gen_Incertae sedis_Unknownia"))
  expect_true(is_placeholder("Aspergillus_sp_HMC1"))
  expect_true(is_placeholder("Fungi sp."))
})
